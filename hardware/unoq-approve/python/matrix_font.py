HEIGHT = 7


def glyph(ch: str) -> tuple[str, ...]:
    ch = {"’": "'", "‘": "'"}.get(ch, ch)
    return GLYPHS.get(ch.upper(), GLYPHS["?"])


def columns(text: str, spacing: int = 1) -> list[int]:
    """The text as a list of columns. Bit r of a column is row r (row 0 at the top)."""
    cols: list[int] = []
    for i, ch in enumerate(text):
        g = glyph(ch)
        for x in range(len(g[0])):
            cols.append(sum(1 << r for r in range(HEIGHT) if g[r][x] == "#"))
        if i != len(text) - 1:
            cols.extend([0] * spacing)
    return cols
